from dotenv import load_dotenv
from agents import Runner
from agents_team import junior_agent, senior_agent, final_agent

# load all the environment variables from .env file
load_dotenv()

while True:
    # get input from user
    # user_input = input("> ")
    user_input = "write a python code to sort a list of 1000 values with best performance"
    if user_input in ['exit', 'quit']:
        break

    # send the requirements to the first agent
    junior_response = Runner.run_sync(
        starting_agent=junior_agent,
        input=user_input,
    )
    print(f"-- junior agent result --")
    print(junior_response.final_output)
    print("-" * 80)

    # send the requirements to the first agent
    senior_response = Runner.run_sync(
        starting_agent=senior_agent,
        input=user_input,
    )
    print(f"-- senior agent result --")
    print(senior_response.final_output)
    print("-" * 80)

    # generate the input prompt
    prompt = f"""
    Following is the requirement asked by user.

    {user_input}

    Following are the code snippets generated by two agents.

    junior_agent: 
    {junior_response.final_output}

    senior_agent:
    {senior_response.final_output}

    Choose the best code snippet based on the performance and security perspectives.
    """

    # send both the answers to the final_agent
    final_response = Runner.run_sync(
        starting_agent=final_agent,
        input=prompt
    )

    print(f"--- final answer ---")
    print(final_response.final_output)
    print('-' * 80)

    break

        