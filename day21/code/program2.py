import asyncio
from agent_framework import Agent
from agent_framework.ollama import OllamaChatClient
from config import MODEL

async def main():
    # create a client
    ollama_client = OllamaChatClient(model=MODEL)

    # create the agent
    agent = Agent(
        name="Storyteller",
        instructions="You are a good story teller. Write a small story on the topic given by user.",
        client=ollama_client
    )

    # get the topic input from user
    topic = input("enter your topic to generate story> ")

    # send the topic to the agent and get the response as it generates
    # stream the output generated by the agent to the console
    async for chunk in agent.run(topic, stream=True):
        if chunk.text:
            print(chunk.text, end="")
    print()

if __name__ == '__main__':
    asyncio.run(main())