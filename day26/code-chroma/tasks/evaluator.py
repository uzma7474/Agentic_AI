from crewai import Task
from app_agents.evaluator import evaluator_agent
from pydantic import BaseModel, Field

# set the expected output structure
class ExpectedResult(BaseModel):
    groundedness: float = Field(ge=0, le=1, description="How well the answer is supported by the retrieved context.")
    relevance: float = Field(ge=0, le=1, description="How well the answer addresses the user's question.")
    completeness: float = Field(ge=0, le=1, description="How completely the answer addresses the question.")
    citation_quality: float = Field(ge=0, le=1, description="How well the answer identifies or references its sources.")
    overall_score: float = Field(ge=0, le=1, description="Overall quality score.")
    passed: bool = Field(description="Whether the answer meets the quality threshold.")
    issues: list[str] = Field(description="Specific problems found in the answer.")
    feedback: list[str] = Field(description="Actionable feedback for improving the answer.")
    recommended_action: str = Field(description="Recommended next action: PASS, REGENERATE, or RETRIEVE_AGAIN.")
    

# create the task for evaluating the result generated by generator agent
evaluation_task = Task(
    description="""
        You are evaluating a RAG-generated answer.

        User Question:
        {question}

        Retrieved Context:
        --------------------
        {context}
        --------------------

        Generated Answer:
        --------------------
        {answer}
        --------------------

        Evaluate the answer using ONLY the retrieved context.

        Evaluate the following:

        1. Groundedness
        - Are the factual claims supported by the retrieved context?
        - Penalize unsupported claims and hallucinations.

        2. Relevance
        - Does the answer directly address the user's question?
        - Penalize irrelevant information.

        3. Completeness
        - Does the answer contain the important information required to answer the question?

        4. Citation Quality
        - Does the answer correctly identify the source information?
        - Penalize unsupported source references.

        5. Overall Quality
        - Calculate an overall score between 0 and 1.

        Use these guidelines:

        0.90 - 1.00 = Excellent
        0.75 - 0.89 = Good
        0.60 - 0.74 = Needs improvement
        Below 0.60 = Poor

        The answer should PASS only when:
        - groundedness >= 0.90
        - relevance >= 0.90
        - completeness >= 0.85
        - overall_score >= 0.90

        If the retrieved context does not contain enough information, recommend RETRIEVE_AGAIN.
        If the context contains the required information but the answer is incorrect or incomplete, recommend REGENERATE.
        If everything is satisfactory, recommend PASS.

        Provide specific and actionable feedback that an optimizer agent can use to improve the RAG pipeline.
    """,

    # set the expectation
    expected_output="""
        A structured evaluation containing:

        - groundedness score
        - relevance score
        - completeness score
        - citation quality score
        - overall score
        - pass/fail decision
        - specific issues
        - actionable feedback
        - recommended action
    """,

    # set the agent
    agent=evaluator_agent,

    # set the structured output
    output_pydantic=ExpectedResult
)